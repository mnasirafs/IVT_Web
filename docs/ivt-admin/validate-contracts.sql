UNION ALL SELECT 'TYPE MISMATCH', e.proc_name, e.param_name + ': database ' + TYPE_NAME(p.user_type_id) + ', module sends ' + e.type_name FROM @expected_test e
  JOIN sys.parameters p ON p.object_id = OBJECT_ID(e.proc_name) AND p.name = e.param_name WHERE TYPE_NAME(p.user_type_id) <> e.type_name
UNION ALL SELECT 'PARAMETER NOT SENT (uses default)', x.proc_name, p.name + ' ' + TYPE_NAME(p.user_type_id) FROM (SELECT DISTINCT proc_name FROM @expected_test) x
  JOIN sys.parameters p ON p.object_id = OBJECT_ID(x.proc_name) WHERE NOT EXISTS (SELECT 1 FROM @expected_test e WHERE e.proc_name = x.proc_name AND e.param_name = p.name)
UNION ALL SELECT 'UNRESOLVED REFERENCE (table may not exist)', x.proc_name, ISNULL(d.referenced_database_name + '.', '') + ISNULL(d.referenced_schema_name + '.', '') + d.referenced_entity_name
  FROM (SELECT DISTINCT proc_name FROM @expected_test) x JOIN sys.sql_expression_dependencies d ON d.referencing_id = OBJECT_ID(x.proc_name)
